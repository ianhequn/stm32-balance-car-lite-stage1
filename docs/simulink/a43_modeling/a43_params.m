%% a43_params.m
% 参数来自/对应喵呜实验室 A43「数学建模」页的简化倒立摆模型。
% 教程把两轮小车近似为高度 L、质量 m 的倒立摆，核心传递函数为：
%     H(s) = 1 / (s^2 - g/L)
% 加入比例、微分反馈后，闭环分母变为：
%     s^2 + (k2/L)s + (k1-g)/L

clear; clc;

g = 9.81;          % 重力加速度，单位 m/s^2

% A43 原文只给符号 L、m，没有给小霸王 Lite 的实测 L。
% 这里先用一个可解释估计值：轮轴到整车重心约 10.5cm。
% 后续你可以用尺子估计实际重心高度后替换。
L = 0.105;         % 倒立摆等效高度，单位 m

% A43 的稳定条件是 k1 > g, k2 > 0。
% 这里故意取一组略大于 g 的 k1 和正的 k2，验证可稳定。
k1 = 16.0;         % 角度反馈等效系数，必须大于 g
k2 = 2.8;          % 角速度反馈等效阻尼，必须大于 0

% 仿真时间
Tstop = 8.0;

% 扰动脉冲：用 3s 到 4s 的短脉冲模拟“轻推一下小车”
disturb_time = 3.0;
disturb_width = 1.0;
disturb_amp = 1.0;

% 传递函数分母
open_den = [1 0 -g/L];
closed_den = [1 k2/L (k1-g)/L];
